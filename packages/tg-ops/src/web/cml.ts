import { posix } from "node:path";

/**
 * The console's CML registry (`packages/tg-web/src/index.cml.ts`): one import per
 * `.xml` template, exported as one array. Generated, because a missing template
 * renders silently as an unknown tag; `test/webCml.test.ts` catches drift.
 */

/** `cml/app/Page.SignIn.xml` → `Page_SignIn`, a legal identifier per file. */
export const importName = (file: string): string =>
  posix.basename(file, ".xml").replace(/[^A-Za-z0-9_$]/g, "_");

/**
 * `files` are paths relative to the generated module's directory, such as
 * `../cml/app/App.xml`. Sorted, so the output is the same on every machine.
 */
export function cmlIndexSource(files: readonly string[]): string {
  const sorted = [...files].sort();
  const names = sorted.map(importName);
  const duplicate = names.find((name, index) => names.indexOf(name) !== index);
  if (duplicate !== undefined) throw new Error(`two templates import as ${duplicate}`);

  return [
    "// GENERATED by scripts/web.ts from packages/tg-web/cml — do not edit.",
    ...sorted.map((file, index) => `import ${names[index]} from "${file}";`),
    "",
    // Biome's own layout, so `biome check --write` leaves the file unchanged.
    "export default [",
    ...names.map((name) => `  ${name},`),
    "];",
    "",
  ].join("\n");
}
